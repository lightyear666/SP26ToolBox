"""队伍配色：0-6 固定，7-31 用黄金角生成，保证任意 team 都有稳定且互异的颜色。"""

BASE = {
    0: ((240, 240, 240), (255, 255, 255)),
    1: ((200, 200, 120), (255, 255, 200)),
    2: ((255, 64, 64), (255, 170, 170)),
    3: ((255, 150, 40), (255, 210, 140)),
    4: ((255, 220, 60), (255, 245, 170)),
    5: ((255, 90, 200), (255, 190, 235)),
    6: ((190, 120, 255), (225, 190, 255)),
}


def tint(c, f=0.45):
    return tuple(int(c[i] + (255 - c[i]) * f) for i in range(3))


def _hsv(h, s, v):
    i = int(h * 6) % 6
    f = h * 6 - int(h * 6)
    p = v * (1 - s)
    q = v * (1 - f * s)
    t = v * (1 - (1 - f) * s)
    r, g, b = ((v, t, p), (q, v, p), (p, v, t),
               (p, q, v), (t, p, v), (v, p, q))[i]
    return int(r * 255), int(g * 255), int(b * 255)


def team_rgb(t):
    t = int(t)
    if t in BASE:
        return BASE[t]
    c = _hsv(((t - 7) * 0.618033988749895 + 0.08) % 1.0, 0.70, 0.96)
    return c, tint(c)
